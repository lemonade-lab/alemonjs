import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const directory = mkdtempSync(join(tmpdir(), 'alemonjs-qq-sanitizer-'));
process.env.CFG_PATH = join(directory, 'config.yaml');
const { getConfig } = await import('alemonjs');
const { sanitizeQQText } = await import('../lib/text-sanitizer.js');
const { register } = await import('../lib/register.js');
const { QQBotAPI } = await import('../lib/sdk/api.js');
const ext = Buffer.from(JSON.stringify({ text: '微笑' })).toString('base64');
const text = ` <@!123> <@123> <@!456> hi\n\n  there [<face,id=14/>] <faceType=1,faceId="1",ext="${ext}"> `;
const result = sanitizeQQText(text, '123', { faces: 'label' });
assert(!result.includes('<@!123>'));
assert(!result.includes('<@123>'));
assert(result.includes('<@!456>'));
assert(result.includes('\n\n  there'));
assert(result.includes('[表情:14]'));
assert(result.includes('[表情:微笑]'));
assert.equal(sanitizeQQText(text, '123', { faces: 'remove', otherMentions: 'remove', collapseWhitespace: true }), 'hi there');
assert.equal(sanitizeQQText(' <@!123> x ', '123', { botMention: 'preserve' }), '<@!123> x');
assert.equal(sanitizeQQText('<@!a.b> <@!axb>', 'a.b'), '<@!axb>', 'Bot IDs are compared literally, not interpolated into a regex');
assert.equal(sanitizeQQText('<faceType=1,faceId="9",ext="invalid">', '123', { faces: 'label' }), '[表情:9]');
assert.equal(sanitizeQQText('[<face,id=14/>]', '123'), '[<face,id=14/>]', 'Faces retain their meaning by default');

const make = config => {
  getConfig().saveValue({ 'qq-bot': config });
  const handlers = new Map();
  const client = new QQBotAPI({ app_id: '123' });
  client.on = (name, handler) => handlers.set(name, handler);
  const events = [];
  register(client, { botId: '123', cbp: { send: event => events.push(event), onactions() {}, onapis() {} } });
  return { handlers, events };
};
const fixture = { id: 'm', content: text, group_openid: 'g', author: { member_openid: 'u' }, mentions: [{ id: '123' }, { id: '456' }] };
const enabled = make({ textSanitizer: { faces: 'label' } });
enabled.handlers.get('GROUP_AT_MESSAGE_CREATE')(fixture);
assert.equal(enabled.events[0].RawMessageText, text);
assert.equal(enabled.events[0].value.content, text);
assert.equal(enabled.events[0].MessageText, result);
assert.equal(enabled.events[0].MessageMentions.length, 2, 'Cleaning text does not discard structured mentions');
enabled.handlers.get('C2C_MESSAGE_CREATE')({ id: 'c', content: '  hi\n  there [<face,id=14/>]  ', author: { user_openid: 'u' } });
assert.equal(enabled.events[1].MessageText, 'hi\n  there [表情:14]');
const legacy = make({});
legacy.handlers.get('GROUP_AT_MESSAGE_CREATE')(fixture);
assert.equal(legacy.events[0].RawMessageText, undefined);
assert(legacy.events[0].MessageText.includes('[<face,id=14/>]'));
getConfig().dispose();
rmSync(directory, { recursive: true, force: true });
console.log('Verified opt-in QQ markup normalization, literal bot IDs, face labels, raw text preservation and group/C2C adapter delivery.');
process.exit(0);
